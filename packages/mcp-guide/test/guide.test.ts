import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fixturesDir } from '@nitrogen/spec';
import { CALLOUT_TYPES, IMAGE_KEYS, lintPage, buildVaultContext } from '@nitrogen/core';
import { guideSection, INSTRUCTIONS, SECTIONS, formatMd } from '../src/index.ts';

describe('guide', () => {
  const spec = readFileSync(join(fixturesDir, '..', 'SPEC.md'), 'utf8');
  it('covers every callout type, image key and lint code', () => {
    const g = guideSection();
    for (const t of CALLOUT_TYPES) expect(g).toContain(t);
    for (const k of IMAGE_KEYS) expect(g).toContain(k);
    for (const code of spec.match(/\b[EW]\d{3}\b/g)!) expect(g).toContain(code);
    for (const s of SECTIONS) expect(guideSection(s).length).toBeGreaterThan(50);
  });
  it('keeps the MCP instructions short', () => {
    expect(INSTRUCTIONS.split(/\s+/).length).toBeLessThan(450);
  });
  it('example page lints clean apart from link targets', () => {
    const ex = guideSection('examples');
    const page = /````md\n([\s\S]*?)\n````/.exec(ex)![1]!;
    const ctx = buildVaultContext([]);
    const codes = lintPage(page, ctx, { path: 'decisions/adr-005.md' }).map((d) => d.code);
    expect(codes.filter((c) => c.startsWith('E'))).toEqual([]);
  });
  it('renders FORMAT.md', () => expect(formatMd()).toMatch(/^<!-- Generated by Nitrogen/));
});
